#include<iostream>

using namespace std;

int main() {
    int num1 , num2;

    cout<<"enter the value of num1:\n";
    cin>>num1;

    cout<<"enter the value of num2:\n";
    cin>>num2;

    cout<<"the sum is:\n"<<num1+num2<<"\n";

    cout<<"the difference is:\n"<<num1-num2<<"\n";

    return 0;
}

//<< is called insertion operator and >> is called extraction operator.